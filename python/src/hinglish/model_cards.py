"""Generate docs/MODEL_CARD_E1..E4.md from saved manifests and metrics only.

    python -m hinglish.model_cards

Numbers in the cards are never typed by hand; a missing artifact renders as
"not run". Re-run after any training/evaluation.
"""
from __future__ import annotations

import json
from pathlib import Path

from .config import load_config

STATIC = {
    "E1": {
        "title": "E1 — Word TF-IDF + Multinomial Logistic Regression (Scala + Spark MLlib)",
        "arch": "Spark ML Pipeline: RegexTokenizer(\\s+, no lowercasing) → CountVectorizer(vocab 20,000) → IDF → "
                "LogisticRegression(family=multinomial, maxIter=100, regParam=0). Fitted on the training split "
                "only and persisted as a PipelineModel (tokenizer, vocabulary, IDF and classifier together).",
        "scores": "Spark's multinomial probabilities, served as `model_probability`. They are NOT calibrated and, "
                  "because the model is unregularised, are extremely over-confident (see the probabilistic "
                  "metrics); the UI labels them 'top class score (uncalibrated)'.",
        "limits": ["Bag of words: no word order, so contrast/negation structure is invisible.",
                   "Unregularised (regParam=0, the midterm definition was kept): over-confident probabilities."],
    },
    "E2": {
        "title": "E2 — Word + character 3-gram TF-IDF + One-vs-Rest LinearSVC (Scala + Spark MLlib)",
        "arch": "Word TF-IDF as E1 plus genuine character 3-grams (CharacterSplitter → NGram(3) → CountVectorizer(20,000) "
                "→ IDF), concatenated by VectorAssembler, classified by OneVsRest(LinearSVC(maxIter=100)) because "
                "LinearSVC is binary-only in Spark MLlib.",
        "scores": "Raw per-class SVM margins are not probabilities. A temperature softmax(m / T) fitted on the "
                  "validation split maps them to calibrated class scores; it preserves the argmax, so the served "
                  "class is always the native One-vs-Rest decision.",
        "limits": ["Linear model over n-grams: limited handling of long-range contrast.",
                   "Character n-grams help with Romanized spelling variation but also pick up noise."],
    },
    "E3": {
        "title": "E3 — XLM-RoBERTa base, fine-tuned (generic multilingual pretraining)",
        "arch": "FacebookAI/xlm-roberta-base (≈278M parameters, 250k-token SentencePiece vocabulary) with a sequence "
                "classification head; fine-tuned with the shared `hinglish.train` entry point.",
        "scores": "Softmax over logits divided by a temperature fitted on the validation split (`calibration.json`); "
                  "served as `calibrated_probability`.",
        "limits": ["Pretrained on generic multilingual CommonCrawl, not on Romanized Hindi-English code-mixing.",
                   "Fine-tuned on stemmed, stop-word-filtered text; raw input is mapped into that space at serving time."],
    },
    "E4": {
        "title": "E4 — HingRoBERTa, fine-tuned (Hindi-English domain-adapted pretraining)",
        "arch": "l3cube-pune/hing-roberta (XLM-RoBERTa architecture further pretrained on the L3Cube HingCorpus of "
                "code-mixed Hindi-English tweets) with a sequence classification head; same entry point and settings "
                "as E3 — only the checkpoint differs.",
        "scores": "Temperature-scaled softmax fitted on the validation split; served as `calibrated_probability`.",
        "limits": ["Domain-adapted on Roman-script tweets; behaviour on formal text or Devanagari is untested here.",
                   "Fine-tuned on stemmed, stop-word-filtered text; raw input is mapped into that space at serving time."],
    },
}


def _pct(v):
    return "not run" if v is None else f"{100 * v:.2f}%"


def _num(v, d=4):
    return "not run" if v is None else f"{v:.{d}f}"


def _load(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def card(cfg, exp: str) -> str:
    key = "spark" if exp in ("E1", "E2") else "transformer"
    run = cfg.path("paths", "models_dir") / exp.lower() / cfg.get(key, "run_tag", default="v2-clean-split")
    m = _load(run / "manifest.json") or {}
    mdir = cfg.path("paths", "metrics_dir")
    test = _load(mdir / f"{exp.lower()}_test_metrics.json")
    if test and m and test.get("model_version") != m.get("version"):
        test = None
    s = STATIC[exp]
    ds = m.get("dataset") or {}
    vm = m.get("validation_metrics") or {}
    tm = (test or {}).get("metrics") or {}
    hp = m.get("hyperparameters") or {}
    lines = [f"# Model card: {s['title']}", "",
             "_Generated by `python -m hinglish.model_cards` from saved artifacts; `not run` = no artifact._", "",
             "## Identity", "",
             f"- Experiment: **{exp}** · version `{m.get('version', 'not trained')}`",
             f"- Base checkpoint: `{m.get('source_checkpoint') or 'n/a (trained from scratch on the task)'}`"
             + (f" (Hub commit `{m['source_checkpoint_revision']}`)" if m.get("source_checkpoint_revision") else ""),
             f"- Training status: {(m.get('status') or {}).get('training', 'not run')} · selection: "
             f"{(m.get('status') or {}).get('selection', '-')} · locked test: "
             f"{'completed' if test else 'not run'}",
             f"- Artifact size: {m.get('artifact_size_bytes', 0) / 2**20:.1f} MB · training runtime: "
             f"{_num(m.get('training_runtime_seconds'), 0)} s" if m else "- Not trained.",
             "", "## Intended use", "",
             "Research and teaching demonstration of sentence-level 3-class sentiment (negative / neutral / positive) "
             "for Romanized Hindi-English code-mixed social-media text, as part of the HinglishSense E1–E4 comparison.",
             "", "## Out of scope", "",
             "Decisions about individuals (moderation, hiring, credit, health, legal); measuring anyone's real "
             "feelings; Devanagari or non-Hinglish text; long documents; any use that treats the score as ground truth.",
             "", "## Training data", "",
             f"SemEval-2020 Task 9 SentiMix Hinglish as supplied (already lowercased, NLTK-stop-word-filtered and "
             f"Porter-stemmed upstream), pooled, de-duplicated and split 80/10/10 with seed 42 "
             f"(train {ds.get('train_rows', '-')}, validation {ds.get('validation_rows', '-')}, "
             f"test {ds.get('test_rows', '-')}). Split manifest SHA-256 `{ds.get('split_manifest_sha256', '-')}`; "
             f"test sample-id hash `{ds.get('test_sample_ids_sha256', '-')}`. See `docs/DATASET_CARD.md`.",
             "", "## Model", "", s["arch"], "",
             "Hyperparameters: " + (", ".join(f"`{k}={v}`" for k, v in hp.items()) or "not run"),
             "", "## Scores shown to users", "", s["scores"],
             "", "## Evaluation", "",
             "| Split | Accuracy | Macro-F1 | Weighted-F1 | Macro-P | Macro-R |", "|---|---:|---:|---:|---:|---:|",
             f"| validation (selection/reporting) | {_pct(vm.get('accuracy'))} | {_pct(vm.get('macro_f1'))} | "
             f"{_pct(vm.get('weighted_f1'))} | {_pct(vm.get('macro_precision'))} | {_pct(vm.get('macro_recall'))} |",
             f"| **test (locked, {(test or {}).get('n_samples', '-')} tweets)** | {_pct(tm.get('accuracy'))} | "
             f"**{_pct(tm.get('macro_f1'))}** | {_pct(tm.get('weighted_f1'))} | {_pct(tm.get('macro_precision'))} | "
             f"{_pct(tm.get('macro_recall'))} |", ""]
    if tm.get("per_class"):
        lines += ["Per class (test):", "", "| Class | Precision | Recall | F1 | Support |", "|---|---:|---:|---:|---:|"]
        for name, pc in tm["per_class"].items():
            lines.append(f"| {name} | {_pct(pc['precision'])} | {_pct(pc['recall'])} | {_pct(pc['f1'])} | {pc['support']} |")
        lines += ["", f"Confusion matrix (rows = true, cols = predicted; {', '.join(tm['labels_order'])}): "
                      f"`{tm['confusion_matrix']}`", ""]
    prob = (test or {}).get("probabilistic") or {}
    if prob:
        lines += ["Probabilistic quality on test:", ""]
        for k, v in prob.items():
            if isinstance(v, dict):
                lines.append(f"- {k}: log-loss {_num(v.get('log_loss'))}, Brier {_num(v.get('brier_multiclass'))}, "
                             f"ECE(15) {_num(v.get('ece_15_bins'))}")
        lines.append("")
    if m.get("training_log"):
        lines += ["Validation curve (per epoch): " + ", ".join(
            f"ep{int(h['epoch'])}: {100 * h['eval_macro_f1']:.2f}%" for h in m["training_log"]) +
            f" — selected epoch {m.get('selected_epoch')}.", ""]
    lines += ["## Limitations and bias", ""] + [f"- {x}" for x in s["limits"]] + [
        "- English negators and contrast words (`not`, `no`, `but`) were removed from the data upstream, so no "
        "model can use them; Hindi ones (`nahi`, `mat`, `lekin`) remain.",
        "- Tweets from one collection period; political and religious topics are heavily represented, and the "
        "neutral class is noisy. Errors are not uniform across topics.",
        "- One split and one seed; no estimate of seed variance.",
        "", "## Licence / provenance", "",
        "Dataset: SemEval-2020 Task 9 (Patwa et al., 2020) — redistribution terms must be checked before sharing "
        "data or derived weights. Base checkpoints: see their Hugging Face model cards (licences not re-verified "
        "here). Fine-tuned weights are not published by this project.", ""]
    return "\n".join(lines)


def main() -> int:
    cfg = load_config()
    for exp in ("E1", "E2", "E3", "E4"):
        out = cfg.root / "docs" / f"MODEL_CARD_{exp}.md"
        out.write_text(card(cfg, exp), encoding="utf-8")
        print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
