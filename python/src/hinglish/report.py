"""Machine-generated E1-E4 comparison + shared error analysis.

    python -m hinglish.report

Everything is DERIVED from saved artifacts (model manifests, *_test_metrics.json,
*_validation_metrics.json, prediction CSVs). A model without a completed
locked test evaluation is reported as ``not run`` -- never filled in.

Outputs:
  artifacts/metrics/comparison_table.{csv,json,md}
  artifacts/error_analysis/errors_all_models.csv
  artifacts/error_analysis/error_summary.json
  artifacts/error_analysis/ERROR_ANALYSIS_REPORT.md
"""
from __future__ import annotations

import json
import math
import time
from pathlib import Path

import pandas as pd

from .config import load_config
from .error_analysis import _CONTRAST_HINT_RE, _EMOJI_RE, _NEGATION_HINT_RE, _romanized_mixed_script_hint
from .prepare_data import load_processed_split

EXPS = ["E1", "E2", "E3", "E4"]


def _load_json(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def _run_dir(cfg, exp):
    key = "spark" if exp in ("E1", "E2") else "transformer"
    return cfg.path("paths", "models_dir") / exp.lower() / cfg.get(key, "run_tag", default="v2-clean-split")


def _sel(cfg, exp):
    m = _load_json(_run_dir(cfg, exp) / "manifest.json") or {}
    e = m.get("selected_epoch")
    return int(e) if isinstance(e, (int, float)) else "n/a"


def collect_rows(cfg) -> list[dict]:
    mdir = cfg.path("paths", "metrics_dir")
    rows = []
    for exp in EXPS:
        manifest = _load_json(_run_dir(cfg, exp) / "manifest.json")
        test = _load_json(mdir / f"{exp.lower()}_test_metrics.json")
        val = _load_json(mdir / f"{exp.lower()}_validation_metrics.json")
        row = {
            "experiment": exp,
            "model": (manifest or {}).get("display_name", "-"),
            "model_version": (manifest or {}).get("version"),
            "training_status": ((manifest or {}).get("status") or {}).get("training", "not run"),
            "test_status": "completed" if test and test.get("status") == "completed" else "not run",
            "evaluation_split": "test (locked)" if test else "-",
        }
        tm = (test or {}).get("metrics", {})
        for k in ("accuracy", "macro_precision", "macro_recall", "macro_f1", "weighted_f1"):
            row[f"test_{k}"] = tm.get(k)
        row["validation_macro_f1"] = ((val or {}).get("metrics") or {}).get("macro_f1")
        for name in ("negative", "neutral", "positive"):
            row[f"test_f1_{name}"] = (tm.get("per_class", {}).get(name) or {}).get("f1")
        prob = (test or {}).get("probabilistic") or {}
        best = prob.get("calibrated") or prob.get("model_probability")
        row["test_log_loss"] = (best or {}).get("log_loss")
        row["test_ece"] = (best or {}).get("ece_15_bins")
        row["score_semantics"] = (manifest or {}).get("score_semantics", "-")
        row["training_runtime_seconds"] = (manifest or {}).get("training_runtime_seconds")
        row["model_size_bytes"] = (manifest or {}).get("artifact_size_bytes")
        row["test_rows"] = (test or {}).get("n_samples")
        row["test_sample_ids_sha256"] = ((test or {}).get("split_identity") or {}).get("test_sample_ids_sha256")
        rows.append(row)
    return rows


def _fmt(v, pct=False):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "not run"
    if pct:
        return f"{100 * v:.2f}%"
    if isinstance(v, float):
        return f"{v:.4f}"
    return str(v)


def write_comparison(cfg, rows: list[dict]) -> str:
    mdir = cfg.path("paths", "metrics_dir")
    df = pd.DataFrame(rows)
    df.to_csv(mdir / "comparison_table.csv", index=False)
    (mdir / "comparison_table.json").write_text(json.dumps({"generated_at_unix": time.time(), "rows": rows},
                                                           indent=2), encoding="utf-8")
    lines = ["# E1-E4 comparison (machine-generated)", "",
             "Generated by `python -m hinglish.report` from saved artifacts only. "
             "`not run` means the artifact does not exist; it is never a zero.", "",
             "| Exp | Model | Split | Accuracy | Macro-F1 | Weighted-F1 | F1 neg | F1 neu | F1 pos | Val Macro-F1 | Log-loss | ECE |",
             "|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in rows:
        lines.append(
            f"| {r['experiment']} | {r['model']} | {r['evaluation_split']} | {_fmt(r['test_accuracy'], True)} | "
            f"{_fmt(r['test_macro_f1'], True)} | {_fmt(r['test_weighted_f1'], True)} | {_fmt(r['test_f1_negative'], True)} | "
            f"{_fmt(r['test_f1_neutral'], True)} | {_fmt(r['test_f1_positive'], True)} | "
            f"{_fmt(r['validation_macro_f1'], True)} | {_fmt(r['test_log_loss'])} | {_fmt(r['test_ece'])} |")
    by = {r["experiment"]: r for r in rows}
    e3, e4 = by["E3"], by["E4"]
    lines += ["", "## Research question: E4 (domain-adapted) vs E3 (generic multilingual)", ""]
    if e3["test_macro_f1"] is not None and e4["test_macro_f1"] is not None:
        d = 100 * (e4["test_macro_f1"] - e3["test_macro_f1"])
        da = 100 * (e4["test_accuracy"] - e3["test_accuracy"])
        lines.append(f"On the locked test split ({e4['test_rows']} samples), E4 - E3 = **{d:+.2f} pp Macro-F1** "
                     f"and {da:+.2f} pp accuracy, under the matched protocol (same split, seed, sequence length, "
                     "batch size, learning rate, optimizer, max epochs (5) and early-stopping/selection rule; only the "
                     "checkpoint differs). Selected epochs: E3 " + str(_sel(cfg, "E3")) + ", E4 " + str(_sel(cfg, "E4")) + ".")
        sig = _load_json(mdir / "e3_e4_significance.json")
        if sig:
            lines.append(f"Paired bootstrap ({sig['n_bootstrap']} resamples) 95% CI for the Macro-F1 difference: "
                         f"[{100 * sig['ci_low']:+.2f}, {100 * sig['ci_high']:+.2f}] pp; "
                         f"McNemar exact p = {sig['mcnemar_p']:.4g}.")
    else:
        lines.append("Not available: E3 and/or E4 has no completed locked test evaluation.")
    md = "\n".join(lines) + "\n"
    (mdir / "comparison_report.md").write_text(md, encoding="utf-8")
    return md


def e3_e4_significance(cfg, n_boot: int = 2000, seed: int = 42) -> dict | None:
    """Paired bootstrap CI on the Macro-F1 difference + exact McNemar test."""
    import numpy as np
    from scipy.stats import binomtest
    from sklearn.metrics import f1_score

    pdir = cfg.path("paths", "predictions_dir")
    p3, p4 = pdir / "e3_test_predictions.csv", pdir / "e4_test_predictions.csv"
    if not (p3.exists() and p4.exists() and (cfg.path("paths", "metrics_dir") / "e4_test_metrics.json").exists()):
        return None
    a = pd.read_csv(p3).set_index("sample_id")
    b = pd.read_csv(p4).set_index("sample_id").loc[a.index]
    y, ya, yb = a["gold_label_id"].to_numpy(), a["pred_label_id"].to_numpy(), b["pred_label_id"].to_numpy()
    rng = np.random.default_rng(seed)
    n = len(y)
    diffs = []
    for _ in range(n_boot):
        idx = rng.integers(0, n, n)
        diffs.append(f1_score(y[idx], yb[idx], average="macro") - f1_score(y[idx], ya[idx], average="macro"))
    ca, cb = ya == y, yb == y
    n01, n10 = int(np.sum(~ca & cb)), int(np.sum(ca & ~cb))
    p = binomtest(n01, n01 + n10, 0.5).pvalue if (n01 + n10) else 1.0
    res = {"n_bootstrap": n_boot, "seed": seed,
           "macro_f1_diff_e4_minus_e3": float(f1_score(y, yb, average="macro") - f1_score(y, ya, average="macro")),
           "ci_low": float(np.percentile(diffs, 2.5)), "ci_high": float(np.percentile(diffs, 97.5)),
           "mcnemar_e4_right_e3_wrong": n01, "mcnemar_e3_right_e4_wrong": n10, "mcnemar_p": float(p)}
    (cfg.path("paths", "metrics_dir") / "e3_e4_significance.json").write_text(json.dumps(res, indent=2), encoding="utf-8")
    return res


def error_analysis(cfg) -> dict:
    """Heuristic (NOT manual) category hints over test errors of every evaluated model."""
    labels = cfg.labels
    test = load_processed_split(cfg, "test").set_index("sample_id")
    out_dir = cfg.path("paths", "error_analysis_dir")
    out_dir.mkdir(parents=True, exist_ok=True)
    frames, summary = [], {}
    for exp in EXPS:
        p = cfg.path("paths", "predictions_dir") / f"{exp.lower()}_test_predictions.csv"
        if not p.exists() or not (cfg.path("paths", "metrics_dir") / f"{exp.lower()}_test_metrics.json").exists():
            summary[exp] = "not run"
            continue
        df = pd.read_csv(p).set_index("sample_id")
        df["text"] = test.loc[df.index, "normalized_text"]
        df["experiment"] = exp
        frames.append(df)
    if not frames:
        return summary
    allp = pd.concat(frames).reset_index()
    t = allp["text"].astype(str)
    allp["hint_negation"] = t.str.contains(_NEGATION_HINT_RE)
    allp["hint_contrast"] = t.str.contains(_CONTRAST_HINT_RE)
    allp["hint_emoji"] = t.str.contains(_EMOJI_RE)
    allp["hint_code_mixing"] = t.map(_romanized_mixed_script_hint)
    allp["hint_short_text"] = t.str.split().str.len() <= 4
    allp["correct"] = allp["gold_label_id"] == allp["pred_label_id"]
    hints = ["hint_negation", "hint_contrast", "hint_emoji", "hint_code_mixing", "hint_short_text"]
    for exp, g in allp.groupby("experiment"):
        s = {"n": int(len(g)), "error_rate": float(1 - g["correct"].mean()), "by_hint": {}}
        for h in hints:
            sub = g[g[h]]
            s["by_hint"][h] = {"n": int(len(sub)),
                               "error_rate": float(1 - sub["correct"].mean()) if len(sub) else None}
        conf = pd.crosstab(g["gold_label_id"].map(labels.id_to_label), g["pred_label_id"].map(labels.id_to_label))
        s["confusions"] = {f"{a}->{b}": int(conf.loc[a, b]) for a in conf.index for b in conf.columns if a != b}
        summary[exp] = s
    errs = allp[~allp["correct"]].copy()
    errs["gold_label"] = errs["gold_label_id"].map(labels.id_to_label)
    errs["pred_label"] = errs["pred_label_id"].map(labels.id_to_label)
    errs[["experiment", "sample_id", "text", "gold_label", "pred_label"] + hints].to_csv(
        out_dir / "errors_all_models.csv", index=False)
    (out_dir / "error_summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")

    lines = ["# Error analysis (locked test split, machine-generated)", "",
             "Categories are **heuristic hints** (regex/lexicon), not manual annotations, and do not claim to "
             "explain why a model erred. Text is the preprocessed (lowercased, stemmed, stopword-filtered) form, so "
             "English negators such as `not`/`no` and the contrast word `but` were removed upstream -- the negation/"
             "contrast hints therefore only fire on Hindi markers (`nahi`, `mat`, `lekin`, `par`, ...).", ""]
    lines.append("| Exp | Error rate | " + " | ".join(h.replace("hint_", "") + " (n / err)" for h in hints) + " |")
    lines.append("|---|---:|" + "---:|" * len(hints))
    for exp, s in summary.items():
        if isinstance(s, str):
            lines.append(f"| {exp} | {s} |" + " |" * len(hints))
            continue
        cells = []
        for h in hints:
            v = s["by_hint"][h]
            cells.append(f"{v['n']} / {100 * v['error_rate']:.1f}%" if v["error_rate"] is not None else "0 / -")
        lines.append(f"| {exp} | {100 * s['error_rate']:.1f}% | " + " | ".join(cells) + " |")
    lines += ["", "## Most frequent confusions", ""]
    for exp, s in summary.items():
        if isinstance(s, dict):
            top = sorted(s["confusions"].items(), key=lambda kv: -kv[1])[:3]
            lines.append(f"- **{exp}**: " + ", ".join(f"{k} ({v})" for k, v in top))
    (out_dir / "ERROR_ANALYSIS_REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return summary


def main() -> int:
    cfg = load_config()
    sig = e3_e4_significance(cfg)
    md = write_comparison(cfg, collect_rows(cfg))
    error_analysis(cfg)
    print(md)
    if sig:
        print(json.dumps(sig, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
